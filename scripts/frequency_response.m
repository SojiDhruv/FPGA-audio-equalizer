function [h_lp, h_mp, h_hp, windowed_lp, windowed_mp, windowed_hp] ...
    = frequency_response(n, N, wc, window)

    % delay shift
    D = (N - 1) / 2;
    m = n - D;

    % Inverse DTFT
    h_lp = integral(@(w) exp(1j*w*m), -wc.wc_bass_high, wc.wc_bass_high, ...
            'ArrayValued', true) ...
            / (2*pi);

    h_mp = (integral(@(w) exp(1j*w*m), -wc.wc_mid_high, -wc.wc_mid_low, ...
            'ArrayValued', true) ...
            + integral(@(w) exp(1j*w*m), wc.wc_mid_low, wc.wc_mid_high, ...
            'ArrayValued', true)) ...
            / (2*pi);

    h_hp = (integral(@(w) exp(1j*w*m), -wc.wc_treble_high, -wc.wc_treble_low, ...
            'ArrayValued', true) ...
            + integral(@(w) exp(1j*w*m), wc.wc_treble_low, wc.wc_treble_high, ...
            'ArrayValued', true)) ...
            / (2*pi);
    
    % apply window
    windowed_lp = h_lp .* window;
    windowed_mp = h_mp .* window;
    windowed_hp = h_hp .* window;
end